import assert from 'node:assert/strict';
import fs from 'node:fs';

const report=JSON.parse(fs.readFileSync('audit-reports/v265-stay-hokkaido-photo-rights.json','utf8'));
const sitemap=fs.readFileSync('site/sitemap.xml','utf8');
const robots=fs.readFileSync('site/robots.txt','utf8');
const source=JSON.parse(fs.readFileSync('site/images/v167/noboribetsu-onsen-lawsonstu-cc0-2015.source.json','utf8'));
assert.match(robots,/Sitemap:\s*https:\/\/www\.nipponferry\.com\/sitemap\.xml/);
assert.equal(report.pages.length,1);
assert.equal(report.pages.reduce((n,p)=>n+p.withheldImgPositions+p.withheldCssHeroPositions,0),4);
assert.equal(source.photographer,'Lawsonstu');
assert.equal(source.captured,'2015-04-07');
assert.equal(source.license,'CC0-1.0');
assert.equal(source.source_page,'https://commons.wikimedia.org/wiki/File:Noboribetsu_Onsen_hot_spring.jpg');
assert.deepEqual(source.saved_pixels,[1280,720]);
for(const item of report.pages){
 const html=fs.readFileSync(item.path,'utf8');
 const url='/stay/hokkaido/';
 assert.equal(html.match(/<h1>([^<]+)<\/h1>/)?.[1],item.originalH1,'H1 changed');
 assert.match(html,/<title>[^<]{20,}<\/title>/,'title missing');
 assert.match(html,/<meta name=['"]description['"] content=['"][^'"]{30,}['"]/,'description missing');
 assert.ok(html.includes("rel='canonical' href='"+item.originalCanonical+"'"),'canonical changed');
 assert.match(html,/<meta name=['"]robots['"] content=['"]index,follow/,'robots changed');
 assert.ok(sitemap.includes('<loc>'+item.originalCanonical+'</loc>'),'sitemap missing');
 assert.doesNotMatch(html,/\/stay\/assets\//,'unverified photo reference');
 assert.equal((html.match(/role='img' aria-label='숙박 예시 사진 게시 보류/g)||[]).length,3,'3 holds required');
 assert.equal((html.match(/<div class='sv-photo-hold sv-photo-hold--card'/g)||[]).length,2,'2 card holds required');
 assert.equal((html.match(/<div class='sv-img sv-photo-hold sv-photo-hold--feature'/g)||[]).length,1,'feature hold required');
 assert.equal((html.match(/id="nf-v265-photo-hold-style"/g)||[]).length,1,'CSS missing');
 assert.ok(html.includes('숙박 예시 사진 3곳과 상단 배경 사진 1곳은 원본 저작자'),'notice missing');
 const hero=html.match(/\.sv-hero:before\{[^}]+\}/)?.[0]||'';
 assert.ok(hero.includes('linear-gradient')&&!hero.includes('url('),'unverified hero photo');
 const cards=[...html.matchAll(/<a class='sv-card' href='([^']+)'/g)].map(m=>m[1]);
 assert.deepEqual(cards,item.originalCardLinks,'card destinations changed');
 const anchors=[...html.matchAll(/<a\b[^>]*\bhref=['"]([^'"]+)['"]/g)].map(m=>m[1]);
 assert.deepEqual(anchors,item.originalAnchorHrefs,'anchor destinations changed');
 assert.equal(anchors.length,item.originalAnchorCount,'anchor count changed');
 const retained=[...html.matchAll(/<img\b[^>]*src=['"]\/images\/v167\/noboribetsu-onsen-lawsonstu-cc0-2015\.webp['"][^>]*>/g)];
 assert.equal(retained.length,1,'CC0 photo not retained exactly once');
 assert.ok(retained[0][0].includes('숙박 객실이 아님'),'regional image misidentified as room');
 assert.ok(html.includes('노보리베쓰 지역 실사: Lawsonstu, 2015년 촬영'),'photo credit removed');
 assert.ok(html.includes(source.source_page),'original photo URL removed');
 assert.ok(html.includes(source.license_uri),'license URL removed');
 assert.ok(html.includes('특정 숙박시설·객실·노천탕 시설을 촬영한 사진이 아닙니다'),'hotel-photo distinction missing');
 assert.ok(html.includes('href="/booking/japan-cruise/"'),'booking guide removed');
 assert.ok(html.includes('https://willer-travel.com/ko/ferry/'),'ferry CTA removed');
 assert.ok(html.includes('숙소·객실 예약이 아닌 일본 국내 페리 항로 조회'),'booking distinction removed');
 assert.doesNotMatch(html,/kidsstay-v5\.vercel\.app|kids-stay\.com/i,'unverified KidsStay referral');
 assert.ok(html.includes('src="/images/kakao-talk.jpg"'),'Kakao contact missing');
 console.log('V265 STATIC PASS '+url+' | 3 legacy images + CSS hero held; CC0 regional image retained; exact anchors/SEO preserved');
}
const dirs=fs.readdirSync('site/stay',{withFileTypes:true}).filter(x=>x.isDirectory()&&fs.existsSync('site/stay/'+x.name+'/index.html'));
assert.equal(dirs.length+1,28,'28 existing stay pages must remain unchanged');
console.log('V265 STATIC PASS: 1 existing page, 4 unverified photo placements held, 1 CC0 regional scene retained, no new pages.');
