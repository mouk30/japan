import assert from 'node:assert/strict';
import fs from 'node:fs';
const audit=JSON.parse(fs.readFileSync('audit-reports/v271-okinawa-kagoshima-photo-rights.json','utf8'));
const registry=JSON.parse(fs.readFileSync('data/v254/stay-verified-region-photos.json','utf8'));
const sitemap=fs.readFileSync('site/sitemap.xml','utf8');
const robots=fs.readFileSync('site/robots.txt','utf8');
assert.equal(audit.version,'V271');
assert.deepEqual(audit.pages.map(p=>p.slug),['okinawa','kagoshima']);
assert.equal(audit.rights.withheldInlinePositions,2);
assert.equal(audit.rights.withheldCssHeroPositions,0);
assert.equal(audit.rights.replacementPhotosAdded,0);
assert.match(robots,/Sitemap:\s*https:\/\/www\.nipponferry\.com\/sitemap\.xml/);
for(const p of audit.pages){
 const html=fs.readFileSync(p.path,'utf8');
 assert.ok(html.includes('<title>'+p.originalTitle+'</title>'),'title changed '+p.slug);
 assert.ok(html.includes("name='description' content='"+p.originalDescription+"'"),'description changed '+p.slug);
 assert.ok(html.includes('<h1>'+p.originalH1+'</h1>'),'H1 changed '+p.slug);
 assert.ok(html.includes("rel='canonical' href='"+p.originalCanonical+"'"),'canonical changed '+p.slug);
 assert.ok(html.includes("name='robots' content='"+p.originalRobots+"'"),'robots changed '+p.slug);
 assert.ok(sitemap.includes('<loc>'+p.originalCanonical+'</loc>'),'sitemap missing '+p.slug);
 const anchors=[...html.matchAll(/<a\b[^>]*\bhref=['"]([^'"]+)['"]/g)].map(m=>m[1]);
 assert.deepEqual(anchors,p.originalAnchorHrefs,'original links changed '+p.slug);
 const cards=[...html.matchAll(/<a class='sv-card' href='([^']+)'/g)].map(m=>m[1]);
 assert.deepEqual(cards,p.originalCardLinks,'card links changed '+p.slug);
 assert.equal(cards.length,3,'3 cards '+p.slug);
 assert.equal((html.match(/<div class='sv-photo-hold sv-photo-hold--card'/g)||[]).length,1,'missing hold '+p.slug);
 assert.equal((html.match(/role='img' aria-label='숙박 참고 사진 게시 보류/g)||[]).length,1,'hold accessible label '+p.slug);
 assert.equal((html.match(/id="nf-v271-photo-hold-style"/g)||[]).length,1,'responsive hold style '+p.slug);
 assert.equal((html.match(/class="nf-v253-photo-notice"/g)||[]).length,1,'V253 notice '+p.slug);
 assert.equal((html.match(/nf-v254-verified-photo-credit/g)||[]).length,1,'V254 credit '+p.slug);
 assert.ok(html.includes('원본 저작자·정확한 촬영 장소·사용 권한이 확인되지 않아 게시를 보류했습니다.'),'hold reason '+p.slug);
 assert.ok(html.includes('해당 도시의 실제 호텔·객실을 촬영했다는 증빙이 없습니다'),'V253 uncertainty '+p.slug);
 assert.doesNotMatch(html,/<img\b[^>]*src=['"]\/stay\/assets\//,'legacy hotel asset still shown '+p.slug);
 const img=[...html.matchAll(/<img\b[^>]*\bsrc=['"]([^'"]+)['"]/g)].map(m=>m[1]);
 const original=p.originalImageSrcs.slice();
 const idx=original.indexOf('/stay/assets/hotel.jpg');
 assert.ok(idx>=0,'baseline missing legacy hotel '+p.slug);
 original.splice(idx,1);
 assert.deepEqual(img,original,'non-target images changed '+p.slug);
 for(const licensed of p.licensedTourismPhotosRetained){
  const record=Object.values(registry.images).find(x=>x.src===licensed.src);
  assert.ok(record&&record.gitBlobSha===licensed.gitBlobSha,'V254 provenance mismatch '+p.slug);
  assert.equal(record.source,licensed.source);
  assert.equal(record.author,licensed.author);
  assert.equal(record.licenseURL,licensed.licenseURL);
  assert.ok(html.includes(licensed.src),'verified tourism image removed '+p.slug);
  assert.ok(html.includes(licensed.source),'original photo source removed '+p.slug);
  assert.ok(html.includes(licensed.author),'photographer credit removed '+p.slug);
  assert.ok(html.includes(licensed.licenseURL),'license removed '+p.slug);
 }
 const hero=html.match(/\.sv-hero:before\{[^}]+\}/)?.[0]||'';
 assert.equal(hero,p.originalHeroCss,'licensed hero changed '+p.slug);
 assert.ok(html.includes('https://willer-travel.com/ko/ferry/'),'ferry CTA changed '+p.slug);
 assert.match(html,/href=['"]\/booking\/japan-cruise\/['"]/,'ferry booking guide removed '+p.slug);
 assert.doesNotMatch(html,/kidsstay-v5\.vercel\.app|kids-stay\.com/i,'KidsStay boundary '+p.slug);
 console.log('V271 STATIC PASS '+p.slug+': 1 unverified hotel card withheld; '+p.licensedTourismPhotosRetained.length+' credited tourism assets, '+anchors.length+' original anchors, SEO and CTA preserved');
}
const dirs=fs.readdirSync('site/stay',{withFileTypes:true}).filter(x=>x.isDirectory()&&fs.existsSync('site/stay/'+x.name+'/index.html'));
assert.equal(dirs.length+1,28,'existing /stay/ 28-page scope changed');
console.log('V271 STATIC PASS: 2 existing pages, 2 legacy card holds, 4 unique credited tourist photos; no new pages');
