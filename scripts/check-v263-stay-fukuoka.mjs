import assert from 'node:assert/strict';
import fs from 'node:fs';
const report=JSON.parse(fs.readFileSync('audit-reports/v263-stay-fukuoka-photo-hold.json','utf8'));
const sitemap=fs.readFileSync('site/sitemap.xml','utf8');
const robots=fs.readFileSync('site/robots.txt','utf8');
assert.match(robots,/Sitemap:\s*https:\/\/www\.nipponferry\.com\/sitemap\.xml/);
assert.equal(report.pages.length,1);
assert.equal(report.pages.reduce((n,p)=>n+p.withheldImgPositions+p.withheldCssHeroPositions,0),5);
for(const item of report.pages){
 const html=fs.readFileSync(item.path,'utf8');
 const url='/stay/'+item.path.split('/')[2]+'/';
 assert.equal(html.match(/<h1>([^<]+)<\/h1>/)?.[1],item.originalH1,'H1 changed '+url);
 assert.match(html,/<title>[^<]{20,}<\/title>/,'title missing '+url);
 assert.match(html,/<meta name=['"]description['"] content=['"][^'"]{30,}['"]/,'description missing '+url);
 assert.ok(html.includes("rel='canonical' href='"+item.originalCanonical+"'"),'canonical changed '+url);
 assert.match(html,/<meta name=['"]robots['"] content=['"]index,follow/,'robots changed '+url);
 assert.ok(sitemap.includes('<loc>'+item.originalCanonical+'</loc>'),'sitemap missing '+url);
 assert.doesNotMatch(html,/\/stay\/assets\//,'unverified photo reference '+url);
 assert.equal((html.match(/role='img' aria-label='숙박 예시 사진 게시 보류/g)||[]).length,4,'4 holds required '+url);
 assert.equal((html.match(/class='sv-photo-hold sv-photo-hold--card'/g)||[]).length,3,'3 card holds required '+url);
 assert.equal((html.match(/class='sv-img sv-photo-hold sv-photo-hold--feature'/g)||[]).length,1,'feature hold required '+url);
 assert.equal((html.match(/id="nf-v263-photo-hold-style"/g)||[]).length,1,'CSS missing '+url);
 assert.ok(html.includes('이 페이지의 숙박 예시 사진 4곳과 상단 배경 사진 1곳은 원본 저작자'),'truthful notice missing '+url);
 const hero=html.match(/\.sv-hero:before\{[^}]+\}/)?.[0]||'';
 assert.ok(hero.includes('linear-gradient')&&!hero.includes('url('),'unverified hero image '+url);
 const cards=[...html.matchAll(/<a class='sv-card' href='([^']+)'/g)].map(m=>m[1]);
 assert.deepEqual(cards,item.originalCardLinks,'card destinations changed '+url);
 const anchors=[...html.matchAll(/<a\b[^>]*\bhref=['"]([^'"]+)['"]/g)].map(m=>m[1]);
 assert.equal(anchors.length,item.originalAnchorCount,'anchor count changed '+url);
 assert.ok(html.includes('href="/booking/japan-cruise/"'),'booking guide removed '+url);
 assert.ok(html.includes('https://willer-travel.com/ko/ferry/'),'ferry CTA removed '+url);
 assert.ok(html.includes('숙소·객실 예약이 아닌 일본 국내 페리 항로 조회'),'booking distinction removed '+url);
 assert.doesNotMatch(html,/kidsstay-v5\.vercel\.app|kids-stay\.com/i,'unverified KidsStay referral '+url);
 assert.ok(html.includes('src="/images/kakao-talk.jpg"'),'Kakao contact missing '+url);
 console.log('V263 STATIC PASS '+url+' | 4 inline images and CSS hero withheld, links/SEO retained');
}
const dirs=fs.readdirSync('site/stay',{withFileTypes:true}).filter(x=>x.isDirectory()&&fs.existsSync('site/stay/'+x.name+'/index.html'));
assert.equal(dirs.length+1,28,'28 existing stay pages must remain unchanged');
console.log('V263 STATIC PASS: 1 existing page, 5 unverified photo placements withheld, no new pages or rights claim.');
