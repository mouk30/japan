import assert from 'node:assert/strict';
import fs from 'node:fs';

const audit=JSON.parse(fs.readFileSync('audit-reports/v269-nagoya-sendai-photo-evidence.json','utf8'));
const registry=JSON.parse(fs.readFileSync('data/v254/stay-verified-region-photos.json','utf8'));
const sitemap=fs.readFileSync('site/sitemap.xml','utf8');
const robots=fs.readFileSync('site/robots.txt','utf8');
assert.equal(audit.version,'V269');
assert.deepEqual(audit.pages.map(p=>p.slug),['nagoya','sendai']);
assert.equal(audit.rights.unverifiedHotelPlacementsWithheld,6);
assert.equal(audit.rights.replacementPhotosAdded,0);
assert.match(robots,/Sitemap:\s*https:\/\/www\.nipponferry\.com\/sitemap\.xml/);
for(const item of audit.pages){
  const html=fs.readFileSync(item.path,'utf8');
  const licensed=item.licensedTourismPhotoRetained;
  assert.ok(html.includes('<title>'+item.originalTitle+'</title>'),'title changed '+item.slug);
  assert.ok(html.includes("name='description' content='"+item.originalDescription+"'"),'description changed '+item.slug);
  assert.ok(html.includes('<h1>'+item.originalH1+'</h1>'),'H1 changed '+item.slug);
  assert.ok(html.includes("rel='canonical' href='"+item.originalCanonical+"'"),'canonical changed '+item.slug);
  assert.ok(html.includes("name='robots' content='"+item.originalRobots+"'"),'robots changed '+item.slug);
  assert.ok(sitemap.includes('<loc>'+item.originalCanonical+'</loc>'),'sitemap missing '+item.slug);
  const anchors=[...html.matchAll(/<a\b[^>]*\bhref=['"]([^'"]+)['"]/g)].map(m=>m[1]);
  assert.deepEqual(anchors,item.originalAnchorHrefs,'anchor hrefs changed '+item.slug);
  assert.equal(anchors.length,item.originalAnchorCount,'anchor count changed '+item.slug);
  const cards=[...html.matchAll(/<a class='sv-card' href='([^']+)'/g)].map(m=>m[1]);
  assert.deepEqual(cards,item.originalCardLinks,'card hrefs changed '+item.slug);
  assert.equal(cards.length,3);
  assert.equal((html.match(/<div class='sv-photo-hold sv-photo-hold--card'/g)||[]).length,3,'missing holds '+item.slug);
  assert.equal((html.match(/role='img' aria-label='숙박 참고 사진 게시 보류/g)||[]).length,3,'accessibility hold labels missing '+item.slug);
  assert.equal((html.match(/id="nf-v269-photo-hold-style"/g)||[]).length,1,'responsive CSS missing '+item.slug);
  assert.ok(html.includes('원본 저작자·정확한 촬영 장소·이용 허락을 확인할 수 없어 게시를 보류했습니다.'),'hold explanation missing '+item.slug);
  assert.ok(html.includes('해당 도시의 실제 호텔·객실을 촬영했다는 증빙이 없습니다'),'V253 provenance notice missing '+item.slug);
  assert.doesNotMatch(html,/<img\b[^>]*src=['"]\/stay\/assets\//,'unverified legacy photo rendered '+item.slug);
  const imgSources=[...html.matchAll(/<img\b[^>]*\bsrc=['"]([^'"]+)['"]/g)].map(m=>m[1]).sort();
  assert.deepEqual(imgSources,[licensed.src,'/images/kakao-talk.jpg'].sort(),'unexpected image sources '+item.slug);
  assert.ok(html.includes(licensed.src),'V254 tourist photo lost '+item.slug);
  assert.ok(html.includes(licensed.source),'original photo credit missing '+item.slug);
  assert.ok(html.includes(licensed.licenseURL),'license credit missing '+item.slug);
  assert.ok(html.includes(licensed.author),'author credit missing '+item.slug);
  assert.ok(html.includes('숙소 객실')||html.includes('호텔 객실'),'tourism/hotel distinction missing '+item.slug);
  const v254=registry.images[registry.pages[item.slug].main];
  assert.equal(licensed.gitBlobSha,v254.gitBlobSha,'source asset manifest changed '+item.slug);
  assert.equal(licensed.src,v254.src,'tourism photo altered '+item.slug);
  const hero=html.match(/\.sv-hero:before\{[^}]+\}/)?.[0]||'';
  assert.ok(hero.includes('linear-gradient')&&!hero.includes('url('),'unverified hero image '+item.slug);
  assert.match(html,/href=['"]\/booking\/japan-cruise\/['"]/,'ferry booking link missing '+item.slug);
  assert.ok(html.includes('https://willer-travel.com/ko/ferry/'),'ferry CTA missing '+item.slug);
  assert.doesNotMatch(html,/kidsstay-v5\.vercel\.app|kids-stay\.com/i,'KidsStay boundary violated '+item.slug);
  console.log('V269 STATIC PASS '+item.slug+' | 3 holds, 1 licensed non-hotel tourist scene, '+anchors.length+' anchors, SEO/CTA retained');
}
const dirs=fs.readdirSync('site/stay',{withFileTypes:true}).filter(x=>x.isDirectory()&&fs.existsSync('site/stay/'+x.name+'/index.html'));
assert.equal(dirs.length+1,28,'28 existing /stay/ pages must remain unchanged');
console.log('V269 STATIC PASS: two existing pages; six unverified hotel photos withheld, V254 credited tourism retained, no new articles');
